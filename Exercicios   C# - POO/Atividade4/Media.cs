class Media
{
    public Media(double num1, double num2)
    {
        double media = (num1 + num2)/2 ;
        Console.WriteLine($"media de 2: {media}\n");
    }
    public Media(double num1, double num2, double num3)
    {
        double media = (num1 + num2 + num3)/3 ;
        Console.WriteLine($"media de 3: {media}\n");
    }

}